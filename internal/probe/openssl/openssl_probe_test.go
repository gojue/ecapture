// Exercise the real manager with generated assets, but fail constant editing
// before any BPF syscall. A manager can exist without an initialized collection;
// closing the probe must still release its other resources without panicking.
func TestProbe_CloseAfterManagerInitFailure(t *testing.T) {
	names := assets.AssetNames()
	if len(names) == 0 {
		t.Skip("requires generated bytecode and the ebpfassets build tag")
	}
	for _, suffix := range []string{"_core.o", "_noncore.o"} {
		for _, name := range names {
			if !strings.HasSuffix(name, suffix) {
				continue
			}
			t.Run(suffix, func(t *testing.T) {
				bytecode, err := assets.Asset(name)
				if err != nil {
					t.Fatal(err)
				}
				probe, err := NewProbe()
				if err != nil {
					t.Fatal(err)
				}
				cfg := config.NewBaseConfig()
				cfg.SetRuntimeOutput(&outputpipeline.RuntimeDependencies{SuppressDefaultText: true})
				if err := probe.BaseProbe.Initialize(context.Background(), cfg); err != nil {
					t.Fatal(err)
				}
				reader, err := os.CreateTemp(t.TempDir(), "reader")
				if err != nil {
					t.Fatal(err)
				}
				t.Cleanup(func() { _ = reader.Close() })
				probe.TrackReader(reader)
				probe.bpfManager = &manager.Manager{}
				const missingConstant = "ecapture_test_missing_constant"
				err = probe.bpfManager.InitWithOptions(bytes.NewReader(bytecode), manager.Options{
					ConstantEditors: []manager.ConstantEditor{{
						Name: missingConstant, Value: uint64(1), FailOnMissing: true,
					}},
				})
				if err == nil || !strings.Contains(err.Error(), missingConstant) {
					t.Fatalf("expected missing constant error before collection load, got %v", err)
				}
				for i := 0; i < 2; i++ {
					if err := probe.Close(); err != nil {
						t.Fatalf("Close() attempt %d: %v", i+1, err)
					}
				}
				if _, err := reader.Stat(); !errors.Is(err, os.ErrClosed) {
					t.Fatalf("tracked reader was not closed: %v", err)
				}
			})
			break
		}
	}
}

